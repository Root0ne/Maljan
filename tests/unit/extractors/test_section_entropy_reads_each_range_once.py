"""Section entropy reads each range of the file once, and states the numbers it always stated.

A section table chooses its own ranges: a thousand sections may all name the
same megabyte, or each a slightly different one, and counting each section's
bytes on its own read the file once per section (22.7 s for 1024 sections
over 1 MB). The counts are now taken in one pass over the file for every
distinct range (``maljan.tools.byte_counts``). The numbers must be those the
per-section count gave, to the bit: the replaced code is inlined below
(``pefile``'s ``get_entropy`` for a PE, the ELF loop as it was). The work is
counted (bytes counted), never timed. Every file here is generated by the
test; nothing is a real program.
"""

from __future__ import annotations

import math
import random
import struct
import zlib
from collections import Counter
from io import BytesIO
from typing import Any

import pefile
import pytest

from maljan.extractors import pe_extractor
from maljan.loaders.pe_loader import PELoader
from maljan.reporting.models import PESection
from maljan.tools import byte_counts

# -- the replaced code, as it was -------------------------------------------------


def _old_shannon(data: bytes) -> float:
    if not data:
        return 0.0
    counts = Counter(data)
    total = len(data)
    entropy = 0.0
    for count in counts.values():
        p = count / total
        entropy -= p * math.log2(p)
    return entropy


def _old_elf_sections(blob: bytes) -> list[PESection]:
    from elftools.elf.elffile import ELFFile

    out: list[PESection] = []
    try:
        elf = ELFFile(BytesIO(blob))
        for section in elf.iter_sections():
            data = section.data() if section.data_size else b""
            entropy = _old_shannon(data) if data else 0.0
            flags = []
            sh_flags = int(getattr(section.header, "sh_flags", 0))
            if sh_flags & 0x4:
                flags.append("EXECUTE")
            if sh_flags & 0x1:
                flags.append("WRITE")
            if sh_flags & 0x2:
                flags.append("ALLOC")
            out.append(
                PESection(
                    name=section.name or "(unnamed)",
                    virtual_address=f"0x{int(section.header.sh_addr):08x}",
                    virtual_size=int(section.header.sh_size or 0),
                    raw_size=int(section.header.sh_size or 0),
                    entropy=round(entropy, 3),
                    characteristics="|".join(flags) or f"0x{sh_flags:08x}",
                    is_suspicious=(entropy >= 7.0),
                )
            )
    except Exception:  # noqa: BLE001
        pass
    return out


# -- generated files ------------------------------------------------------------


def _pe(rng: random.Random, count: int, size: int) -> bytes:
    """A PE whose ``count`` sections overlap, repeat, run past the file or hold nothing."""
    headers = (0x80 + 24 + 0xF0 + 40 * count + 0x1FF) // 0x200 * 0x200
    body = bytes(rng.choice(b"\0\0AB\xff") for _ in range(size // 2)) + rng.randbytes(size // 2)
    header = bytearray(headers)
    header[0:2] = b"MZ"
    struct.pack_into("<I", header, 0x3C, 0x80)
    struct.pack_into("<4sHHIIIHH", header, 0x80, b"PE\0\0", 0x8664, count, 0, 0, 0, 0xF0, 0x22)
    optional = 0x80 + 24
    struct.pack_into("<H", header, optional, 0x20B)
    struct.pack_into("<Q", header, optional + 24, 0x140000000)
    alignment = rng.choice([0x200, 0x1000, 0x10])
    struct.pack_into("<II", header, optional + 32, alignment, rng.choice([0x200, 0x10]))
    struct.pack_into("<I", header, optional + 56, 0x100000)
    struct.pack_into("<I", header, optional + 60, headers)
    struct.pack_into("<I", header, optional + 108, 16)
    for index in range(count):
        offset = headers + rng.choice([0, 0, 0x200, rng.randrange(0, size), size + 0x400])
        raw_size = rng.choice([size, size // 3, 0, rng.randrange(0, size + 0x800), 0x7FFFFFFF])
        rva = rng.choice([0x1000 * (index + 1), offset])
        struct.pack_into(
            "<8sIIIIIIHHI", header, optional + 0xF0 + 40 * index, f".s{index}".encode(),
            raw_size, rva, raw_size, offset, 0, 0, 0, 0, rng.choice([0x40000040, 0x60000020]),
        )  # fmt: skip
    return bytes(header) + body


def _elf(rng: random.Random, count: int, size: int, only: int | None = None) -> bytes:
    """A 64-bit ELF whose sections overlap, repeat, hold no bytes, are compressed or run out."""
    body = rng.randbytes(size // 2) + bytes(rng.choice(b"\0AB") for _ in range(size // 2))
    names = b"\0.shstrtab\0" + b"".join(f".s{i}\0".encode() for i in range(count))
    compressed = struct.pack("<IIQQ", 1, 0, 300, 1) + zlib.compress(body[:300])
    names_at = 64 + len(body)
    compressed_at = names_at + len(names)
    table = compressed_at + len(compressed)
    table += -table % 8
    head = bytearray(64)
    head[0:7] = b"\x7fELF\x02\x01\x01"
    struct.pack_into(
        "<HHIQQQIHHHHHH", head, 16, 2, 0x3E, 1, 0, 0, table, 0, 64, 0, 0, 64, count + 2, 1
    )
    headers = bytearray(64 * (count + 2))
    struct.pack_into("<IIQQQQIIQQ", headers, 64, 1, 3, 0, 0, names_at, len(names), 0, 0, 1, 0)
    name = len(b"\0.shstrtab\0")
    for index in range(count):
        kind, flags, offset, length = 1, 0x2, 64, len(body)
        pick = rng.randrange(6) if only is None else only
        if pick == 1:
            offset, length = 64 + rng.randrange(size), rng.randrange(size)
        elif pick == 2:
            kind, length = 8, rng.choice([0, 100, 1 << 16, (1 << 64) - 1])
        elif pick == 3:
            offset, length, flags = compressed_at, len(compressed), 0x802
        elif pick == 4:
            offset, length = table + 10_000, 50
        struct.pack_into(
            "<IIQQQQIIQQ", headers, 64 * (index + 2), name, kind, flags, 0x1000 * index,
            offset, length, 0, 0, 16, 0,
        )  # fmt: skip
        name += len(f".s{index}\0")
    blob = bytes(head) + body + names + compressed
    return blob + bytes(table - len(blob)) + bytes(headers)


# -- the same numbers -------------------------------------------------------------


@pytest.mark.parametrize("seed", range(10))
def test_range_counts_are_a_counters_counts_in_its_order(seed: int) -> None:
    rng = random.Random(seed)
    data = rng.randbytes(rng.randrange(1, 3000)) + bytes(rng.randrange(50))
    spans: list[tuple[int, int]] = []
    for _ in range(30):
        low, high = sorted(rng.randrange(len(data) + 1) for _ in range(2))
        spans.append((low, high))
    spans += [(0, len(data)), (0, 0), (len(data), len(data))]
    counts = byte_counts.range_counts(data, spans)
    for start, stop in spans:
        assert counts.get((start, stop), []) == list(Counter(data[start:stop]).values())


@pytest.mark.parametrize("seed", range(12))
def test_a_pe_section_s_entropy_is_pefile_s(seed: int) -> None:
    rng = random.Random(seed)
    blob = _pe(rng, rng.randint(1, 12), rng.choice([64, 900, 5000]))
    pe = pefile.PE(data=blob, fast_load=True)
    assert byte_counts.pefile_section_entropies(pe) == [s.get_entropy() for s in pe.sections]
    for section in pe.sections:
        start, stop = byte_counts.pefile_section_span(section, len(blob))
        assert blob[start:stop] == section.get_data()


@pytest.mark.parametrize("seed", range(12))
def test_an_elf_section_table_reads_as_it_did(seed: int) -> None:
    rng = random.Random(seed)
    blob = _elf(rng, rng.randint(1, 10), rng.choice([64, 900, 5000]))
    new = [s.model_dump() for s in pe_extractor._parse_elf_sections(blob)]
    assert new == [s.model_dump() for s in _old_elf_sections(blob)]


def test_the_pe_loader_states_pefile_s_entropy(tmp_path: Any) -> None:
    blob = _pe(random.Random(3), 9, 4000)
    path = tmp_path / "sample.bin"
    path.write_bytes(blob)
    pe = pefile.PE(data=blob, fast_load=True)
    rows = PELoader(str(path))._get_sections()
    assert [row["entropy"] for row in rows] == [round(s.get_entropy(), 2) for s in pe.sections]


# -- each range once --------------------------------------------------------------


def _overlapping_pe(count: int, size: int, shift: int) -> bytes:
    headers = (0x80 + 24 + 0xF0 + 40 * count + 0x1FF) // 0x200 * 0x200
    header = bytearray(headers)
    header[0:2] = b"MZ"
    struct.pack_into("<I", header, 0x3C, 0x80)
    struct.pack_into("<4sHHIIIHH", header, 0x80, b"PE\0\0", 0x8664, count, 0, 0, 0, 0xF0, 0x22)
    optional = 0x80 + 24
    struct.pack_into("<H", header, optional, 0x20B)
    struct.pack_into("<Q", header, optional + 24, 0x140000000)
    struct.pack_into("<II", header, optional + 32, 0x1000, 0x200)
    struct.pack_into("<II", header, optional + 56, 0x10000000, headers)
    for index in range(count):
        struct.pack_into(
            "<8sIIIIIIHHI", header, optional + 0xF0 + 40 * index, b".s", size,
            0x1000 * (index + 1), size, headers + shift * index, 0, 0, 0, 0, 0x40000040,
        )  # fmt: skip
    return bytes(header) + random.Random(count).randbytes(size + shift * count)


def _read_once(size: int) -> int:
    """The most bytes the counts may read: the file once, two blocks per range answered."""
    return size + 2 * byte_counts.BLOCK * byte_counts.WORK["ranges"]


@pytest.mark.parametrize("shift", [0, 1, 3, 0x200])
def test_overlapping_pe_sections_count_the_file_once(shift: int) -> None:
    blob = _overlapping_pe(200, 64 * 1024, shift)
    byte_counts.WORK.clear()
    sections = pe_extractor._parse_pe(blob).sections
    assert len(sections) == 200
    assert byte_counts.WORK["ranges"] <= 200
    assert byte_counts.WORK["bytes"] <= _read_once(len(blob))
    pe = pefile.PE(data=blob, fast_load=True)
    assert byte_counts.pefile_section_entropies(pe) == [s.get_entropy() for s in pe.sections]


def _extended_elf(count: int, length: int) -> bytes:
    """An ELF whose section count is in section 0 (``e_shnum`` 0): ``count`` sections at
    offsets one byte apart, each ``length`` bytes long."""
    rng = random.Random(1)
    data = rng.randbytes(length + count) + b"\0"
    table = 64 + len(data)
    head = b"\x7fELF\x02\x01\x01" + bytes(9)
    head += struct.pack("<HHIQQQIHHHHHH", 2, 62, 1, 0, 0, table, 0, 64, 56, 0, 64, 0, 1)
    rows = struct.pack("<IIQQQQIIQQ", 0, 0, 0, 0, 0, count + 2, 0, 0, 0, 0)
    rows += struct.pack("<IIQQQQIIQQ", 0, 3, 0, 0, table - 1, 1, 0, 0, 1, 0)
    rows += b"".join(
        struct.pack("<IIQQQQIIQQ", 0, 1, 2, 0x1000, 64 + k, length, 0, 0, 1, 0)
        for k in range(count)
    )
    return head + data + rows


def test_sections_one_byte_apart_cost_the_file_and_the_sections_not_their_product() -> None:
    import tracemalloc

    count, length = 4_000, 8192
    blob = _extended_elf(count, length)
    spans = [(64 + k, 64 + k + length) for k in range(count)]
    byte_counts.WORK.clear()
    tracemalloc.start()
    try:
        entropies = byte_counts.range_entropies(blob, spans, byte_counts.counter_entropy)
        peak = tracemalloc.get_traced_memory()[1]
    finally:
        tracemalloc.stop()
    assert len(entropies) == count
    assert byte_counts.WORK["ranges"] == count
    assert byte_counts.WORK["bytes"] <= _read_once(len(blob))
    # The checkpoints hold about the file once, each range keeps one number,
    # and the working arrays of one window come on top whatever the file.
    assert peak <= 3 * len(blob) + 400 * count + 32 * byte_counts.STRETCH
    sample = random.Random(2).sample(spans, 50)
    for span in sample:
        assert entropies[span] == _old_shannon(blob[span[0] : span[1]])
    sections = pe_extractor._parse_elf_sections(blob)
    assert len(sections) == count + 2


def test_overlapping_elf_sections_count_the_file_once() -> None:
    blob = _elf(random.Random(0), 1, 64 * 1024)
    # 300 sections, all naming the same range.
    count = 300
    table = struct.unpack_from("<Q", blob, 0x28)[0]
    first = blob[table + 128 : table + 192]
    names_at = struct.unpack_from("<Q", blob, table + 64 + 24)[0]
    head = bytearray(blob[:64])
    struct.pack_into("<H", head, 0x3C, count + 2)
    plain = bytearray(first)
    struct.pack_into("<IIQQQQ", plain, 0, 1, 1, 0x2, 0, 64, 32 * 1024)
    rebuilt = bytes(head) + blob[64:table] + blob[table : table + 128] + bytes(plain) * count
    assert names_at < table
    byte_counts.WORK.clear()
    sections = pe_extractor._parse_elf_sections(rebuilt)
    assert len(sections) == count + 2
    assert byte_counts.WORK["bytes"] <= _read_once(len(rebuilt))
    assert [s.model_dump() for s in sections] == [
        s.model_dump() for s in _old_elf_sections(rebuilt)
    ]


def test_carving_after_the_static_analysis_does_not_parse_again(
    tmp_path: Any, monkeypatch: pytest.MonkeyPatch
) -> None:
    blob = _overlapping_pe(3, 4096, 0x200) + b"PK\x03\x04" + bytes(2000)
    path = tmp_path / "sample.bin"
    path.write_bytes(blob)
    pe_extractor.reset_static_analysis_cache()
    cold = pe_extractor.carve_payloads(blob)
    pe_extractor.reset_static_analysis_cache()
    pe_extractor.build_static_analysis(sample_path=str(path))
    parses: list[int] = []
    real = pe_extractor._parse_pe

    def counted(data: bytes) -> object:
        parses.append(1)
        return real(data)

    monkeypatch.setattr(pe_extractor, "_parse_pe", counted)
    assert pe_extractor.carve_payloads(blob) == cold
    assert parses == []
    pe_extractor.reset_static_analysis_cache()


# -- compressed sections: inflated as they stream, once per range, to a stated cap --


def test_compressed_sections_naming_one_range_inflate_it_once(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    blob = _elf(random.Random(4), 40, 4000, only=3)
    calls: list[int] = []
    real = pe_extractor._inflated_entropy

    def counted(section: Any, inflation: Any) -> float:
        calls.append(1)
        return real(section, inflation)

    monkeypatch.setattr(pe_extractor, "_inflated_entropy", counted)
    sections = pe_extractor._parse_elf_sections(blob)
    assert len(sections) == 42
    assert calls == [1]
    assert [s.model_dump() for s in sections] == [s.model_dump() for s in _old_elf_sections(blob)]


class _CountingInflater:
    """A zlib decompressor that counts the bytes it hands out."""

    inflated = 0

    def __init__(self) -> None:
        self._inner = _DECOMPRESSOBJ()

    def decompress(self, data: bytes, max_length: int = 0) -> bytes:
        out = self._inner.decompress(data, max_length)
        _CountingInflater.inflated += len(out)
        return out

    @property
    def unconsumed_tail(self) -> bytes:
        return self._inner.unconsumed_tail


_DECOMPRESSOBJ = zlib.decompressobj


def test_compressed_sections_past_the_cap_stop_the_table_and_say_so(
    tmp_path: Any, monkeypatch: pytest.MonkeyPatch
) -> None:
    from maljan.tools import binary

    # Each compressed section is its own range (the size differs), 300 bytes inflated.
    blob = bytearray(_elf(random.Random(4), 6, 4000, only=3))
    table = struct.unpack_from("<Q", blob, 0x28)[0]
    for index in range(6):
        at = table + 64 * (index + 2) + 32
        struct.pack_into("<Q", blob, at, struct.unpack_from("<Q", blob, at)[0] + index)
    assert pe_extractor.ELF_INFLATE_CAP == pe_extractor.SAMPLE_UPLOAD_MAX_BYTES
    monkeypatch.setattr(pe_extractor, "ELF_INFLATE_CAP", 1000)
    monkeypatch.setattr(pe_extractor.zlib, "decompressobj", _CountingInflater)
    _CountingInflater.inflated = 0

    sections, stopped = pe_extractor._elf_sections(bytes(blob))

    # Three sections of 300 bytes fit in 1000; the fourth would pass it.
    assert len(sections) == 2 + 3
    assert "stops before section 5" in stopped and "1000 bytes" in stopped
    assert _CountingInflater.inflated <= 1000 + 300
    path = tmp_path / "sample.elf"
    path.write_bytes(bytes(blob))
    assert binary.elf_info(str(path))["sections_stopped"] == stopped
    pe_extractor.reset_static_analysis_cache()
    analysis = pe_extractor.build_static_analysis(sample_path=str(path))
    assert analysis is not None and analysis.sections_partial == [stopped]
    pe_extractor.reset_static_analysis_cache()
