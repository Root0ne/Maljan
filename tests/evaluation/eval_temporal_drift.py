_GROUND_TRUTH_DIR = _REPO_ROOT / "tests" / "evaluation" / "ground_truth" / "attck_malware"
_SAMPLES_DIR = _REPO_ROOT / "data" / "samples"

# MalwareBazaar family signatures concatenate words ("AgentTesla"); the ATT&CK
# fixture slug spaces+underscores them ("agent_tesla"). The slug fallbacks below
# handle most cases; this explicit map pins the ones whose word boundaries the
# heuristic can't recover (e.g. "RedLineStealer" -> "RedLine Stealer").
_FAMILY_ALIASES: dict[str, str] = {
    "agenttesla": "agent_tesla",
    "cobaltstrike": "cobalt_strike",
    "redlinestealer": "redline_stealer",
    "smokeloader": "smoke_loader",
    "azorult": "azorult",
    "lokibot": "lokibot",
    "loki": "lokibot",
    "njrat": "njrat",
    "qakbot": "qakbot",
    "quasarrat": "quasarrat",
    "asyncrat": "asyncrat",
    "nanocore": "nanocore",
}


# ---------------------------------------------------------------------------
# Pure helpers (network-free, LLM-free — unit-tested)
# ---------------------------------------------------------------------------


def _slugify(name: str) -> str:
    """Match ``prepare_attck_malware_fixtures._slugify`` exactly."""
    slug = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    return slug[:72]


def _camel_split(name: str) -> str:
    """Insert spaces at lower->Upper and letter->digit boundaries.

    'AgentTesla' -> 'Agent Tesla', 'njRAT' -> 'nj RAT'. Lets a concatenated
    MalwareBazaar signature recover the spaced ATT&CK family name before slugging.
    """
    spaced = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", name)
    spaced = re.sub(r"(?<=[A-Za-z])(?=[0-9])", " ", spaced)
    return spaced


def resolve_fixture_slug(signature: str, available: set[str]) -> str | None:
    """Resolve a MalwareBazaar family signature to an available fixture slug.

    Tries, in order: the explicit alias map, the direct slug, and the
    CamelCase-split slug. Returns None when none match an available fixture
    (the sample then counts as ``no_ground_truth``).
    """
    sig = (signature or "").strip()
    if not sig:
        return None
    alias = _FAMILY_ALIASES.get(sig.lower())
    if alias and alias in available:
        return alias
    for cand in (_slugify(sig), _slugify(_camel_split(sig))):
        if cand in available:
            return cand
    return None


def available_fixture_slugs(gt_dir: Path) -> set[str]:
    """Set of family slugs that have a ground-truth fixture on disk."""
    if not gt_dir.is_dir():
        return set()
    return {p.stem for p in gt_dir.glob("*.json")}


def load_ground_truth(slug: str, gt_dir: Path) -> tuple[set[str], set[str]]:
    """Return (ground_truth_technique_ids, attck_valid_ids) for a family slug."""
    doc = json.loads((gt_dir / f"{slug}.json").read_text(encoding="utf-8"))
    gt = {str(t).upper() for t in doc.get("technique_ids", [])}
    valid = {str(t).upper() for t in doc.get("attck_valid_ids", [])}
    return gt, valid


def locate_binary(sha256: str, samples_dir: Path) -> Path | None:
    """Find ``<sha256>.<ext>`` under samples_dir (any extension), or None."""
    if not samples_dir.is_dir():
        return None
    for p in samples_dir.glob(f"{sha256}.*"):
        if p.is_file():
            return p
    return None


def extract_predicted_tids(result: Any) -> set[str]:
    """Pull the pipeline's predicted ATT&CK technique IDs from a run result.

    Unions the per-agent ISR claim techniques with the cascade-corroborated
    techniques in the run summary, tolerating both object and dict shapes so the
    extractor is testable without a live run.
    """
    out: set[str] = set()

    def _get(obj: Any, key: str, default: Any = None) -> Any:
        if isinstance(obj, dict):
            return obj.get(key, default)
        return getattr(obj, key, default)

    isr_reports = _get(result, "isr_reports", {}) or {}
    values = isr_reports.values() if isinstance(isr_reports, dict) else isr_reports
    for isr in values:
        for claim in _get(isr, "claims", []) or []:
            tid = _get(claim, "technique_id", None)
            if tid:
                out.add(str(tid).upper())

    summary = _get(result, "run_summary", {}) or {}
    cascade = _get(summary, "cascade", {}) or {}
    for tid in _get(cascade, "corroborated_techniques", []) or []:
        if tid:
            out.add(str(tid).upper())
    return out


def _mean(xs: list[float]) -> float:
    return sum(xs) / len(xs) if xs else 0.0


def _bootstrap_ci(values: list[float], iters: int = 2000) -> tuple[float, float]:
    """Percentile bootstrap 95% CI for the mean. Deterministic (fixed LCG)."""
    n = len(values)
    if n < 2:
        return (0.0, 0.0)
    means: list[float] = []
    seed = 0x9E3779B9
    for _ in range(iters):
        acc = 0.0
        for _ in range(n):
            seed = (1103515245 * seed + 12345) & 0x7FFFFFFF
            acc += values[seed % n]
        means.append(acc / n)
    means.sort()
    return (means[int(0.025 * iters)], means[int(0.975 * iters)])


@dataclass
class SampleScore:
    """One scored sample within a year cohort."""

    year: str
    sha256: str
    family: str
    precision: float
    recall: float
    f1: float
    hallucination_rate: float
    n_predicted: int
    n_ground_truth: int

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def score_sample(
    year: str,
    sha256: str,
    family: str,
    predicted: set[str],
    ground_truth: set[str],
    valid_ids: set[str],
) -> SampleScore:
    """Build a SampleScore from predicted vs ground-truth technique sets."""
    m = TTPAccuracyMetrics(
        predicted_ttps=set(predicted),
        ground_truth_ttps=set(ground_truth),
        attck_valid_ttps=set(valid_ids) if valid_ids else None,
    )
    hr = m.hallucination_rate
    return SampleScore(
        year=year,
        sha256=sha256,
        family=family,
        precision=m.precision,
        recall=m.recall,
        f1=m.f1,
        hallucination_rate=hr if hr is not None else 0.0,
        n_predicted=len(m.predicted_ttps),
        n_ground_truth=len(m.ground_truth_ttps),
    )


def aggregate_by_cohort(scores: list[SampleScore]) -> OrderedDict[str, dict[str, Any]]:
    """Per-year mean precision/recall/F1 (+95% CI) and counts, years ascending."""
    by_year: dict[str, list[SampleScore]] = {}
    for s in scores:
        by_year.setdefault(s.year, []).append(s)
    out: OrderedDict[str, dict[str, Any]] = OrderedDict()
    for year in sorted(by_year):
        recs = by_year[year]
        f1s = [r.f1 for r in recs]
        out[year] = {
            "n": len(recs),
            "precision": _mean([r.precision for r in recs]),
            "recall": _mean([r.recall for r in recs]),
            "f1": _mean(f1s),
            "f1_ci": _bootstrap_ci(f1s),
            "hallucination": _mean([r.hallucination_rate for r in recs]),
        }
    return out


def drift_delta(cohorts: OrderedDict[str, dict[str, Any]]) -> dict[str, Any] | None:
    """Earliest vs latest cohort F1 delta (None when <2 cohorts scored)."""
    years = list(cohorts)
    if len(years) < 2:
        return None
    first, last = years[0], years[-1]
    return {
        "earliest_year": first,
        "latest_year": last,
        "earliest_f1": cohorts[first]["f1"],
        "latest_f1": cohorts[last]["f1"],
        "f1_delta": cohorts[last]["f1"] - cohorts[first]["f1"],
    }


# ---------------------------------------------------------------------------
# Manifest loading + live pipeline (the parts that need data / services)
# ---------------------------------------------------------------------------


def load_manifest(path: Path) -> OrderedDict[str, list[dict[str, str]]]:
    """Return {year: [sample dicts]} from a collect_temporal_manifest.py output."""
    doc = json.loads(path.read_text(encoding="utf-8"))
    cohorts = doc.get("cohorts", {})
    return OrderedDict(sorted(cohorts.items()))


def _run_pipeline_on(sha256: str, binary_path: Path, file_name: str) -> set[str]:
    """Run the full Maljan pipeline on one binary; return predicted technique IDs."""
    from maljan.app import MaljanApp
    from maljan.core.config import get_settings

    app = MaljanApp(config=get_settings(), mock=False, samples_dir=str(_SAMPLES_DIR))
    result = app.run(
        file_hash=sha256,
        file_name=file_name,
        sample_path=str(binary_path),
        static_sample_path=str(binary_path),
    )
    return extract_predicted_tids(result)


# ---------------------------------------------------------------------------
# Report
# ---------------------------------------------------------------------------


def _render_report(
    coverage: OrderedDict[str, dict[str, int]],
    cohorts: OrderedDict[str, dict[str, Any]],
    drift: dict[str, Any] | None,
    *,
    dry_run: bool,
) -> str:
    lines = [
        "# Temporal / concept-drift eval (§4 Item 5, MARD)",
        "",
        ("**Dry run** — coverage only; no pipeline executed." if dry_run else "Live pipeline run."),
        "",
        "## Cohort coverage",
        "",
        "| year | manifest | ground-truth resolved | binary present | scored |",
        "|---|---|---|---|---|",
    ]
    for year, c in coverage.items():
        lines.append(
            f"| {year} | {c['manifest']} | {c['gt_resolved']} | "
            f"{c['binary_present']} | {c['scored']} |"
        )
    lines += ["", "## Per-cohort accuracy (scored samples only)", ""]
    if cohorts:
        lines += [
            "| year | n | precision | recall | F1 | 95% F1 CI | hallucination |",
            "|---|---|---|---|---|---|---|",
        ]
        for year, m in cohorts.items():
            lo, hi = m["f1_ci"]
            lines.append(
                f"| {year} | {m['n']} | {m['precision']:.3f} | {m['recall']:.3f} | "
                f"{m['f1']:.3f} | [{lo:.3f}, {hi:.3f}] | {m['hallucination']:.3f} |"
            )
    else:
        lines.append("_No samples scored yet — drop the binaries into data/samples/ and re-run._")
    lines += ["", "## Drift", ""]
    if drift:
        lines.append(
            f"Earliest cohort {drift['earliest_year']} F1={drift['earliest_f1']:.3f} -> "
            f"latest {drift['latest_year']} F1={drift['latest_f1']:.3f} "
            f"(delta {drift['f1_delta']:+.3f})."
        )
    else:
        lines.append("_Need >=2 scored cohorts to measure drift._")
    lines.append("")
    return "\n".join(lines)


