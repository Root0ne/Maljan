"""Temporal / concept-drift eval (findings-log §4 Item 5, MARD).

MARD reports robustness across a multi-year span. This harness slices the dated
manifest produced by ``collect_temporal_manifest.py`` into **first-seen year
cohorts** and reports per-cohort ATT&CK precision / recall / F1 (mean +/- 95%
bootstrap CI), then the earliest->latest drift delta — answering "does the
pipeline's accuracy decay on older / newer malware?".

Ground truth is per-family: each sample's expected technique set is the MITRE
ATT&CK ``uses``-relationship technique list for its family, vendored under
``tests/evaluation/ground_truth/attck_malware/<slug>.json`` (generated by
``scripts/prepare_attck_malware_fixtures.py``). The manifest's MalwareBazaar
``signature`` is mapped to that slug via an explicit alias map + slug fallbacks.

The actual binaries are NOT in the repo (never committed). A sample is scored
only when its ``<sha256>.<ext>`` file is present under ``data/samples/`` AND its
family resolves to a ground-truth fixture; otherwise it is counted as
``pending_binary`` or ``no_ground_truth`` and reported, never silently dropped.

  * ``--dry-run``  — resolve fixtures + check binary presence and print the
                     coverage table only; runs OFFLINE, no pipeline, no LLM.
                     Use this to validate manifest/ground-truth wiring now.
  * (default)      — run the full pipeline on each present binary and score it.
                     Requires a live llama-server + the binaries on disk.

Run:  uv run python tests/evaluation/eval_temporal_drift.py --dry-run
      uv run python tests/evaluation/eval_temporal_drift.py --manifest D:/tmp/manifest.json
      uv run python tests/evaluation/eval_temporal_drift.py --max-per-cohort 10   # cheap first pass
"""

