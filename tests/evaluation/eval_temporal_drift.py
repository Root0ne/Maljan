def main() -> int:
    ap = argparse.ArgumentParser(description="Temporal/concept-drift eval (§4 Item 5).")
    ap.add_argument("--manifest", type=str, default=str(_DEFAULT_MANIFEST))
    ap.add_argument("--dry-run", action="store_true", help="Coverage only; no pipeline/LLM.")
    ap.add_argument("--smoke", action="store_true", help="First present sample only.")
    ap.add_argument(
        "--max-per-cohort",
        type=int,
        default=0,
        help="Cap NEW pipeline runs per cohort this invocation (0 = no cap). Cheap first pass.",
    )
    ap.add_argument(
        "--workers",
        type=int,
        default=1,
        help="Concurrent pipeline runs (default 1; >1 only helps a multi-slot LLM server).",
    )
    ap.add_argument("--checkpoint", type=str, default=str(_DEFAULT_CHECKPOINT))
    args = ap.parse_args()

    manifest_path = Path(args.manifest)
    if not manifest_path.exists():
        print(
            f"Manifest not found: {manifest_path}\n"
            "Run collect_temporal_manifest.py first (--selftest, --source csv, or --source api).",
            flush=True,
        )
        return 2

    manifest = load_manifest(manifest_path)
    available = available_fixture_slugs(_GROUND_TRUTH_DIR)
    print(
        f"Manifest: {sum(len(v) for v in manifest.values())} samples across "
        f"{len(manifest)} cohorts; {len(available)} ground-truth fixtures available.",
        flush=True,
    )

    checkpoint = Path(args.checkpoint)
    scores: list[SampleScore] = []
    done: set[str] = set()
    if checkpoint.exists():
        for line in checkpoint.read_text(encoding="utf-8").splitlines():
            if line.strip():
                rec = json.loads(line)
                done.add(rec["key"])
                scores.append(SampleScore(**{k: v for k, v in rec.items() if k != "key"}))
        print(f"Resume: {len(done)} samples already scored in {checkpoint}.", flush=True)

    # Pass 1: coverage accounting + the analyzable-sample list (full manifest;
    # cap/smoke are applied below, not here).
    coverage, analyzable = scan_manifest(manifest, available, _SAMPLES_DIR, frozenset(done))

    # Apply --max-per-cohort and --smoke to pick which analyzable samples to run.
    tasks: list[tuple[str, str, str, str, Path, str]] = []
    new_per_year: dict[str, int] = {}
    if not args.dry_run:
        for t in analyzable:
            year = t[0]
            if args.max_per_cohort and new_per_year.get(year, 0) >= args.max_per_cohort:
                continue
            if args.smoke and sum(new_per_year.values()) >= 1:
                continue
            new_per_year[year] = new_per_year.get(year, 0) + 1
            tasks.append(t)

    # Pass 2: run the pipeline on each task (optionally concurrent). One bad
    # sample is logged and skipped, never aborting the run.
    if tasks:
        import threading
        from concurrent.futures import ThreadPoolExecutor, as_completed

        lock = threading.Lock()

        def _run_task(task: tuple[str, str, str, str, Path, str]) -> SampleScore | None:
            year, sha, family, slug, binary, fname = task
            gt, valid = load_ground_truth(slug, _GROUND_TRUTH_DIR)
            try:
                # Never score a sample while the LLM is unreachable — a crashed
                # server would yield a meaningless LLM-less result. Wait it out.
                _ensure_llm_healthy()
                predicted = _run_pipeline_on(sha, binary, fname)
            except Exception as exc:  # noqa: BLE001 — isolate per-sample failure
                print(f"  [{year}] {sha[:12]} pipeline failed: {exc}", flush=True)
                return None
            return score_sample(year, sha, family, predicted, gt, valid)

        with ThreadPoolExecutor(max_workers=max(1, args.workers)) as pool:
            futures = {pool.submit(_run_task, t): t for t in tasks}
            for fut in as_completed(futures):
                sc = fut.result()
                if sc is None:
                    continue
                rec = {"key": f"{sc.year}:{sc.sha256}", **sc.to_dict()}
                with lock:
                    scores.append(sc)
                    coverage[sc.year]["scored"] += 1
                    with checkpoint.open("a", encoding="utf-8") as fh:
                        fh.write(json.dumps(rec) + "\n")
                print(f"  [{sc.year}] {sc.sha256[:12]} {sc.family}: F1={sc.f1:.3f}", flush=True)

    cohorts = aggregate_by_cohort(scores)
    drift = drift_delta(cohorts)
    report = _render_report(coverage, cohorts, drift, dry_run=args.dry_run)
    print("\n" + report, flush=True)
    try:
        _OUT_FILE.write_text(report + "\n", encoding="utf-8")
        print(f"\nWrote {_OUT_FILE}", flush=True)
    except OSError:
        pass
    return 0


if __name__ == "__main__":
    sys.exit(main())
