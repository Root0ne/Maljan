"""prepare_tram_dataset.py — Build Maljan ground truth fixtures from TRAM2.

Downloads the TRAM2 single_label.json dataset from the MITRE Center for
Threat-Informed Defense repository, groups entries by threat report document,
and writes one GroundTruth-compatible JSON fixture per unique document to:

    tests/evaluation/ground_truth/tram/

The `attck_valid_ids` field in each fixture is populated from:
  1. `data/attck_valid_ids.json` (generated by prepare_attck_malware_fixtures.py)
     when that file exists — gives the full ~700 active ATT&CK technique universe.
  2. `--attck-valid-ids PATH` argument if provided.
  3. Fallback: the set of technique IDs found in the TRAM2 dataset itself (~50 IDs).

For accurate hallucination rate computation, run prepare_attck_malware_fixtures.py
first to generate data/attck_valid_ids.json before running this script.

Usage:
    uv run python scripts/prepare_tram_dataset.py
    uv run python scripts/prepare_tram_dataset.py --min-techniques 3
    uv run python scripts/prepare_tram_dataset.py --out tests/evaluation/ground_truth/tram/
    uv run python scripts/prepare_tram_dataset.py --attck-valid-ids data/attck_valid_ids.json

Dataset source:
    https://github.com/center-for-threat-informed-defense/tram
    License: Apache-2.0
    Each entry: {"text": "...", "label": "T1055", "doc_title": "..."}
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import urllib.request
from collections import defaultdict
from pathlib import Path
from urllib.parse import urlparse

TRAM2_URL = (
    "https://raw.githubusercontent.com/center-for-threat-informed-defense"
    "/tram/main/data/tram2-data/single_label.json"
)

DEFAULT_OUT_DIR = (
    Path(__file__).resolve().parent.parent / "tests" / "evaluation" / "ground_truth" / "tram"
)

# Minimum unique techniques required for a document to be included.
DEFAULT_MIN_TECHNIQUES = 3

# Optional: full ATT&CK technique universe generated by prepare_attck_malware_fixtures.py
DEFAULT_ATTCK_VALID_IDS_PATH = (
    Path(__file__).resolve().parent.parent / "data" / "attck_valid_ids.json"
)


def _load_attck_valid_ids(path: Path | None) -> set[str] | None:
    """Load the full ATT&CK valid ID universe from a JSON file if available.

    Returns None to signal that the caller should fall back to deriving IDs
    from the TRAM2 dataset itself.
    """
    candidates: list[Path] = []
    if path is not None:
        candidates.append(path)
    candidates.append(DEFAULT_ATTCK_VALID_IDS_PATH)

    for candidate in candidates:
        if candidate.exists():
            try:
                data = json.loads(candidate.read_text(encoding="utf-8"))
                ids: list[str] = data.get("technique_ids", [])
                if ids:
                    print(
                        f"  attck_valid_ids: loaded {len(ids)} IDs from {candidate}",
                        flush=True,
                    )
                    return set(ids)
            except (json.JSONDecodeError, KeyError):
                pass

    print(
        "  attck_valid_ids: data/attck_valid_ids.json not found, "
        "falling back to TRAM2-internal ID set.\n"
        "  Tip: run 'make prepare-attck' first for accurate hallucination rate.",
        flush=True,
    )
    return None


def _slugify(title: str) -> str:
    """Convert a document title to a safe filesystem/fixture identifier."""
    slug = title.lower()
    slug = re.sub(r"[^a-z0-9]+", "_", slug)
    slug = slug.strip("_")
    return slug[:72]


def _fetch_tram2(url: str) -> list[dict[str, str]]:
    """Download and parse the TRAM2 single_label.json file."""
    print(f"Fetching TRAM2 dataset from:\n  {url}", flush=True)
    # ``--url`` is operator-supplied; refuse anything but HTTP(S) so it can
    # never coerce urllib into reading file:// / ftp:// resources.
    scheme = urlparse(url).scheme.lower()
    if scheme not in ("http", "https"):
        print(f"[ERROR] Refusing non-HTTP(S) dataset URL: {url!r}", file=sys.stderr)
        sys.exit(1)
    try:
        # nosemgrep: python.lang.security.audit.dynamic-urllib-use-detected.dynamic-urllib-use-detected — scheme validated above  # noqa: E501
        with urllib.request.urlopen(url, timeout=30) as response:  # noqa: S310
            raw = response.read().decode("utf-8")
    except Exception as exc:
        print(f"[ERROR] Download failed: {exc}", file=sys.stderr)
        sys.exit(1)
    try:
        data: list[dict[str, str]] = json.loads(raw)
    except json.JSONDecodeError as exc:
        print(f"[ERROR] JSON parse failed: {exc}", file=sys.stderr)
        sys.exit(1)
    print(f"  Loaded {len(data):,} labeled sentences.", flush=True)
    return data


def _group_by_document(
    entries: list[dict[str, str]],
) -> dict[str, dict[str, object]]:
    """Group TRAM2 entries by doc_title.

    Returns:
        Mapping of doc_title -> {"technique_ids": set[str], "texts": list[str]}
    """
    groups: dict[str, dict[str, object]] = defaultdict(
        lambda: {"technique_ids": set(), "texts": []}
    )
    for entry in entries:
        title = entry.get("doc_title", "").strip()
        label = entry.get("label", "").strip().upper()
        text = entry.get("text", "").strip()
        if not title or not label:
            continue
        groups[title]["technique_ids"].add(label)  # type: ignore[union-attr]
        groups[title]["texts"].append(text)  # type: ignore[union-attr]
    return dict(groups)


def _build_fixture(
    sample_id: str,
    doc_title: str,
    technique_ids: set[str],
    attck_valid_ids: set[str],
) -> dict[str, object]:
    """Build a GroundTruth-compatible fixture dict."""
    return {
        "sample_id": sample_id,
        "notes": (
            f"TRAM2 ground truth — threat report: '{doc_title}'. "
            f"Source: center-for-threat-informed-defense/tram (Apache-2.0)."
        ),
        "technique_ids": sorted(technique_ids),
        "attck_valid_ids": sorted(attck_valid_ids),
        "expected_stix_types": ["malware", "attack-pattern", "relationship"],
        "expected_rel_types": ["uses"],
    }


def prepare(
    out_dir: Path = DEFAULT_OUT_DIR,
    min_techniques: int = DEFAULT_MIN_TECHNIQUES,
    url: str = TRAM2_URL,
    external_attck_valid_ids: set[str] | None = None,
) -> int:
    """Download TRAM2 and write per-document fixture files.

    Args:
        out_dir: Output directory for fixture JSON files.
        min_techniques: Minimum unique techniques required per document.
        url: URL of the TRAM2 single_label.json file.
        external_attck_valid_ids: Full ATT&CK technique universe to use as
            attck_valid_ids in each fixture. When None, falls back to the
            set of technique IDs found in the TRAM2 dataset itself (~50 IDs).

    Returns:
        Number of fixture files written.
    """
    out_dir.mkdir(parents=True, exist_ok=True)

    entries = _fetch_tram2(url)
    groups = _group_by_document(entries)

    # Collect all technique IDs from the TRAM2 dataset itself.
    tram2_technique_ids: set[str] = set()
    for group in groups.values():
        tram2_technique_ids.update(group["technique_ids"])  # type: ignore[arg-type]

    # Determine the valid ID universe for attck_valid_ids field.
    # Always include TRAM2-observed IDs (some may be revoked in latest ATT&CK,
    # e.g., T1574.002 "DLL Side-Loading" → superseded in ATT&CK v14+).
    # When external catalog is provided, union both sets so that:
    #   - Hallucination detection covers the full current ATT&CK catalog
    #   - Legacy/revoked IDs referenced in threat reports are not misclassified
    if external_attck_valid_ids is not None:
        attck_valid_ids: set[str] = external_attck_valid_ids | tram2_technique_ids
        source_label = f"ATT&CK catalog + TRAM2 union ({len(attck_valid_ids)} IDs)"
    else:
        attck_valid_ids = tram2_technique_ids
        source_label = f"TRAM2 subset ({len(attck_valid_ids)} IDs)"

    print(
        f"\nDataset summary:\n"
        f"  Unique documents      : {len(groups)}\n"
        f"  TRAM2 techniques      : {len(tram2_technique_ids)}\n"
        f"  attck_valid_ids count : {len(attck_valid_ids)} ({source_label})\n",
        flush=True,
    )

    written = 0
    skipped = 0

    for doc_title, group in sorted(groups.items()):
        tech_ids: set[str] = group["technique_ids"]  # type: ignore[assignment]
        if len(tech_ids) < min_techniques:
            skipped += 1
            continue

        sample_id = _slugify(doc_title)
        fixture = _build_fixture(
            sample_id=sample_id,
            doc_title=doc_title,
            technique_ids=tech_ids,
            attck_valid_ids=attck_valid_ids,
        )
        out_path = out_dir / f"{sample_id}.json"
        out_path.write_text(json.dumps(fixture, indent=2, ensure_ascii=False), encoding="utf-8")
        written += 1
        print(f"  [{written:>3}] {sample_id} ({len(tech_ids)} techniques)", flush=True)

    print(
        f"\nDone.\n"
        f"  Written : {written} fixtures  ->  {out_dir}\n"
        f"  Skipped : {skipped} documents (< {min_techniques} unique techniques)\n",
        flush=True,
    )
    return written


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build Maljan ground truth fixtures from the TRAM2 dataset.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=DEFAULT_OUT_DIR,
        help="Output directory for fixture JSON files.",
    )
    parser.add_argument(
        "--min-techniques",
        type=int,
        default=DEFAULT_MIN_TECHNIQUES,
        help="Minimum unique techniques required to include a document.",
    )
    parser.add_argument(
        "--url",
        default=TRAM2_URL,
        help="URL of the TRAM2 single_label.json file.",
    )
    parser.add_argument(
        "--attck-valid-ids",
        type=Path,
        default=None,
        metavar="PATH",
        help=(
            "Path to attck_valid_ids.json generated by prepare_attck_malware_fixtures.py. "
            "If omitted, the script auto-detects data/attck_valid_ids.json."
        ),
    )
    args = parser.parse_args()

    external_ids = _load_attck_valid_ids(args.attck_valid_ids)

    count = prepare(
        out_dir=args.out,
        min_techniques=args.min_techniques,
        url=args.url,
        external_attck_valid_ids=external_ids,
    )
    if count == 0:
        print(
            "[WARNING] No fixtures were written. Check --min-techniques threshold.",
            file=sys.stderr,
        )
        sys.exit(1)


if __name__ == "__main__":
    main()
